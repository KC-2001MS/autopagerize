// Updates siteinfo.js, the SITEINFO snapshot bundled with autopagerize.user.js.
//
// usage:
//   node tools/update-siteinfo.js           download from wedata
//   node tools/update-siteinfo.js <file> [source]
//       convert a local wedata JSON file (or siteinfo.js of AutoPagerize X)
'use strict'

var fs = require('fs')
var http = require('http')
var path = require('path')

var DATA_URL = 'http://wedata.net/databases/AutoPagerize/items_all.json'
var OUTPUT = path.join(__dirname, '..', 'siteinfo.js')
var KNOWN_KEYS = ['url', 'nextLink', 'insertBefore', 'pageElement']

function parse(text) {
    // siteinfo.js of AutoPagerize X: loadLocalSiteinfoCallback([...], "date")
    var start = text.indexOf('[')
    var end = text.lastIndexOf(']')
    return JSON.parse(text.slice(start, end + 1))
}

function reduce(data) {
    var updatedAt = null
    var info = data.filter(function(i) {
        return i && i.data && i.data.url && i.data.nextLink && i.data.pageElement
    }).map(function(i) {
        if (i.updated_at && (!updatedAt || i.updated_at > updatedAt)) {
            updatedAt = i.updated_at
        }
        var item = {}
        KNOWN_KEYS.forEach(function(key) {
            if (i.data[key]) {
                item[key] = i.data[key]
            }
        })
        return item
    })
    info.sort(function(a, b) { return (b.url.length - a.url.length) })
    return { info: info, updatedAt: updatedAt }
}

function write(text, source) {
    var r = reduce(parse(text))
    if (!r.updatedAt) {
        // siteinfo.js of AutoPagerize X has the date as the last argument.
        var m = text.match(/"(\d{4}-\d\d-\d\dT[^"]+)"\s*\)\s*$/)
        r.updatedAt = m ? m[1] : null
    }
    var lines = r.info.map(function(i) { return '    ' + JSON.stringify(i) })
    var out = '// AutoPagerize SITEINFO snapshot, bundled with autopagerize.user.js.\n' +
        '// Generated by tools/update-siteinfo.js. Do not edit by hand.\n' +
        '// source: ' + source + '\n' +
        '// generated: ' + new Date().toISOString() + '\n' +
        '// entries: ' + r.info.length + '\n' +
        'var AUTOPAGERIZE_SITEINFO = {\n' +
        '  "updated_at": ' + JSON.stringify(r.updatedAt) + ',\n' +
        '  "info": [\n' + lines.join(',\n') + '\n  ]\n' +
        '}\n'
    fs.writeFileSync(OUTPUT, out)
    console.log('wrote ' + r.info.length + ' entries to ' + OUTPUT)
}

if (process.argv[2]) {
    write(fs.readFileSync(process.argv[2], 'utf8'),
          process.argv[3] || path.basename(process.argv[2]))
}
else {
    console.log('fetching ' + DATA_URL)
    http.get(DATA_URL, function(res) {
        if (res.statusCode != 200) {
            console.error('HTTP ' + res.statusCode)
            process.exit(1)
        }
        var chunks = []
        res.on('data', function(chunk) { chunks.push(chunk) })
        res.on('end', function() {
            write(Buffer.concat(chunks).toString('utf8'), DATA_URL)
        })
    }).on('error', function(e) {
        console.error(e.message)
        process.exit(1)
    })
}
